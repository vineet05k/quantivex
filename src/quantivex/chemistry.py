"""Molecules to qubit Hamiltonians.

Pipeline: geometry -> RHF -> active space (CASCI integrals) -> spin-orbital
second-quantised Hamiltonian -> Jordan-Wigner qubit operator.

Spin-orbital order is block order: alpha orbitals on qubits 0..n-1, beta
orbitals on qubits n..2n-1. A set bit means the spin orbital is occupied.

Integrals for a grid of standard geometries ship with the package
(`resources/integrals.json.gz`, generated by `scripts/build_integral_cache.py` with
PySCF), so the default workflows run on every platform, including Windows
where PySCF is unavailable. Off-grid geometries need PySCF.
"""

from __future__ import annotations

import gzip
import itertools
import json
import logging
from dataclasses import dataclass
from functools import lru_cache
from importlib import resources
from typing import Any

import numpy as np
from qiskit.quantum_info import SparsePauliOp

from .errors import ChemistryError

log = logging.getLogger(__name__)

BASIS = "sto-3g"
CHEMICAL_ACCURACY_HA = 1.6e-3

# Active orbitals are chosen by symmetry (irreducible representation), not by energy order.
# Energy ordering swaps sigma and pi orbitals as N2 stretches, which silently changes the
# active space between geometries and breaks the potential-energy curve. The Hartree-Fock
# occupation per irrep is fixed for the same reason.
MOLECULES: dict[str, dict[str, Any]] = {
    "N2": {
        "atoms": ("N", "N"),
        "range": (0.7, 3.0),
        "equilibrium": 1.10,
        "irrep_nelec": {"A1g": 6, "A1u": 4, "E1ux": 2, "E1uy": 2, "E1gx": 0, "E1gy": 0},
        # (active orbitals per irrep, core orbitals per irrep)
        "active_spaces": {
            (2, 2): (
                {"A1g": 1, "A1u": 1},  # sigma bond: 3sg, 3su*
                {"A1g": 2, "A1u": 2, "E1ux": 1, "E1uy": 1},
            ),
            (4, 4): (
                {"E1ux": 1, "E1uy": 1, "E1gx": 1, "E1gy": 1},  # pi bonds: 1pu, 1pg*
                {"A1g": 3, "A1u": 2, "E1ux": 0, "E1uy": 0},
            ),
            (6, 6): (
                {"A1g": 1, "A1u": 1, "E1ux": 1, "E1uy": 1, "E1gx": 1, "E1gy": 1},  # triple bond
                {"A1g": 2, "A1u": 2, "E1ux": 0, "E1uy": 0},
            ),
        },
    },
    "H2": {
        "atoms": ("H", "H"),
        "range": (0.3, 3.0),
        "equilibrium": 0.74,
        "irrep_nelec": {"A1g": 2, "A1u": 0},
        "active_spaces": {(2, 2): ({"A1g": 1, "A1u": 1}, {"A1g": 0, "A1u": 0})},
    },
    "LiH": {
        "atoms": ("Li", "H"),
        "range": (0.9, 4.0),
        "equilibrium": 1.60,
        "irrep_nelec": {"A1": 4, "E1x": 0, "E1y": 0},
        "active_spaces": {
            (2, 2): ({"A1": 2}, {"A1": 1}),  # bonding + antibonding sigma
        },
    },
}


@dataclass(frozen=True, eq=False)  # identity hash: safe as an lru_cache key
class ActiveSpaceProblem:
    """One molecule at one geometry in one active space, with reference energies."""

    molecule: str
    bond_length: float
    n_electrons: int
    n_orbitals: int
    e_core: float
    h1: np.ndarray
    eri: np.ndarray  # chemist notation (pq|rs), shape (n, n, n, n)
    e_hf: float
    e_exact: float  # CASCI singlet ground state in the active space (the Hartree-Fock symmetry)
    source: str

    def __post_init__(self) -> None:
        for name in ("h1", "eri"):
            array = np.asarray(getattr(self, name), dtype=float)
            immutable = np.frombuffer(array.tobytes(), dtype=float).reshape(array.shape)
            object.__setattr__(self, name, immutable)

    @property
    def n_qubits(self) -> int:
        return 2 * self.n_orbitals

    @property
    def n_alpha(self) -> int:
        return self.n_electrons // 2

    @property
    def n_beta(self) -> int:
        return self.n_electrons - self.n_alpha

    @property
    def hf_index(self) -> int:
        """Computational-basis index of the Hartree-Fock determinant."""
        bits = list(range(self.n_alpha)) + [self.n_orbitals + i for i in range(self.n_beta)]
        return sum(1 << b for b in bits)

    def describe(self) -> dict[str, Any]:
        return {
            "molecule": self.molecule,
            "bond_length_angstrom": self.bond_length,
            "basis": BASIS,
            "active_space": f"CAS({self.n_electrons}e,{self.n_orbitals}o)",
            "qubits": self.n_qubits,
            "e_hf_hartree": round(self.e_hf, 8),
            "e_exact_hartree": round(self.e_exact, 8),
            "reference_target": "CASCI singlet in Hartree-Fock spatial symmetry; not unrestricted ground state",
            "target_spin_s": 0,
            "target_spin_squared": 0,
            "reference_symmetry": "Hartree-Fock spatial symmetry",
            "correlation_energy_mha": round(1000 * (self.e_exact - self.e_hf), 4),
            "integral_source": self.source,
        }


def _key(molecule: str, bond_length: float, n_electrons: int, n_orbitals: int) -> str:
    return f"{molecule}|{bond_length:.2f}|{n_electrons}|{n_orbitals}"


@lru_cache(maxsize=1)
def _cache() -> dict[str, Any]:
    try:
        blob = resources.files("quantivex").joinpath("resources/integrals.json.gz").read_bytes()
    except FileNotFoundError:
        log.warning("Integral cache not found; PySCF will be required for every geometry")
        return {}
    data: dict[str, Any] = json.loads(gzip.decompress(blob))
    return data


def cached_geometries(molecule: str, n_electrons: int, n_orbitals: int) -> list[float]:
    suffix = f"|{n_electrons}|{n_orbitals}"
    return (
        sorted(
            float(k.split("|")[1]) for k in _cache()["entries"] if k.startswith(molecule + "|") and k.endswith(suffix)
        )
        if _cache()
        else []
    )


def _validate(molecule: str, bond_length: float, n_electrons: int, n_orbitals: int) -> None:
    if molecule not in MOLECULES:
        raise ChemistryError(f"Unknown molecule {molecule!r}; supported: {sorted(MOLECULES)}")
    lo, hi = MOLECULES[molecule]["range"]
    if not lo <= bond_length <= hi:
        raise ChemistryError(f"{molecule} bond length must be in [{lo}, {hi}] angstrom")
    if (n_electrons, n_orbitals) not in MOLECULES[molecule]["active_spaces"]:
        raise ChemistryError(
            f"Active space ({n_electrons}e,{n_orbitals}o) not supported for {molecule}; "
            f"choose from {list(MOLECULES[molecule]['active_spaces'])}"
        )


def compute_with_pyscf(molecule: str, bond_length: float, n_electrons: int, n_orbitals: int) -> ActiveSpaceProblem:
    """Compute active-space integrals with PySCF (Linux/macOS)."""
    try:
        from pyscf import ao2mo, gto, mcscf, scf
    except ImportError as exc:
        raise ChemistryError(
            "This geometry is not in the bundled integral cache and PySCF is not installed "
            "(PySCF is unavailable on Windows; use WSL or Docker). Cached bond lengths: "
            f"{cached_geometries(molecule, n_electrons, n_orbitals)}"
        ) from exc
    spec = MOLECULES[molecule]
    a, b = spec["atoms"]
    mol = gto.M(atom=f"{a} 0 0 0; {b} 0 0 {bond_length}", basis=BASIS, symmetry=True, verbose=0)
    mf = scf.RHF(mol)
    mf.irrep_nelec = dict(spec["irrep_nelec"])
    mf.conv_tol = 1e-11
    mf.kernel()
    if not mf.converged:
        raise ChemistryError(f"RHF did not converge for {molecule} at {bond_length} angstrom")
    mc = mcscf.CASCI(mf, n_orbitals, n_electrons)
    cas_irreps, core_irreps = spec["active_spaces"][(n_electrons, n_orbitals)]
    mo = mcscf.sort_mo_by_irrep(mc, mf.mo_coeff, cas_irreps, core_irreps)
    e_exact = float(mc.kernel(mo)[0])
    h1, e_core = mc.get_h1eff(mo)
    eri = ao2mo.restore(1, mc.get_h2eff(mo), n_orbitals)
    return ActiveSpaceProblem(
        molecule,
        round(bond_length, 4),
        n_electrons,
        n_orbitals,
        float(e_core),
        np.asarray(h1),
        np.asarray(eri),
        float(mf.e_tot),
        e_exact,
        "pyscf",
    )


@lru_cache(maxsize=256)
def get_problem(molecule: str, bond_length: float, n_electrons: int = 2, n_orbitals: int = 2) -> ActiveSpaceProblem:
    """Return the active-space problem, from the bundled cache when possible."""
    _validate(molecule, bond_length, n_electrons, n_orbitals)
    entry = _cache().get("entries", {}).get(_key(molecule, bond_length, n_electrons, n_orbitals))
    if entry is not None and abs(entry["bond_length"] - bond_length) < 1e-9:
        n = n_orbitals
        return ActiveSpaceProblem(
            molecule,
            bond_length,
            n_electrons,
            n_orbitals,
            entry["e_core"],
            np.array(entry["h1"]).reshape(n, n),
            np.array(entry["eri"]).reshape(n, n, n, n),
            entry["e_hf"],
            entry["e_exact"],
            "bundled cache (PySCF " + _cache().get("pyscf_version", "?") + ")",
        )
    return compute_with_pyscf(molecule, bond_length, n_electrons, n_orbitals)


@lru_cache(maxsize=16)
def _ladder(n_qubits: int) -> tuple[tuple[SparsePauliOp, ...], tuple[SparsePauliOp, ...]]:
    """Jordan-Wigner creation and annihilation operators.

    a_j^dagger = Z_0 ... Z_{j-1} (X_j - i Y_j) / 2, which maps |0> to |1> on qubit j.
    """
    create, annihilate = [], []
    for j in range(n_qubits):
        z = "Z" * j
        idx = list(range(j + 1))
        create.append(SparsePauliOp.from_sparse_list([(z + "X", idx, 0.5), (z + "Y", idx, -0.5j)], n_qubits))
        annihilate.append(SparsePauliOp.from_sparse_list([(z + "X", idx, 0.5), (z + "Y", idx, 0.5j)], n_qubits))
    return tuple(create), tuple(annihilate)


def _product(*ops: SparsePauliOp) -> SparsePauliOp:
    """Operator product in written order (leftmost acts last): ops[0] @ ops[1] @ ...

    Note: SparsePauliOp.compose has the opposite convention; dot is the matrix product.
    """
    out = ops[0]
    for op in ops[1:]:
        out = out.dot(op)
    return out


def qubit_hamiltonian(problem: ActiveSpaceProblem) -> SparsePauliOp:
    """Return a defensive copy of the cached Hamiltonian."""
    return _cached_qubit_hamiltonian(problem).copy()


@lru_cache(maxsize=256)
def _cached_qubit_hamiltonian(problem: ActiveSpaceProblem) -> SparsePauliOp:
    """H = E_core + sum h_pq a+_p a_q + 1/2 sum (pq|rs) a+_p a+_r a_s a_q (spin-summed), JW-mapped."""
    n, nq = problem.n_orbitals, problem.n_qubits
    cr, an = _ladder(nq)

    def so(p: int, spin: int) -> int:
        return p + spin * n

    terms = [SparsePauliOp.from_sparse_list([("", [], problem.e_core)], nq)]
    for p, q in itertools.product(range(n), repeat=2):
        if abs(problem.h1[p, q]) > 1e-12:
            for s in (0, 1):
                terms.append(problem.h1[p, q] * _product(cr[so(p, s)], an[so(q, s)]))
    for p, q, r, s_ in itertools.product(range(n), repeat=4):
        v = problem.eri[p, q, r, s_]
        if abs(v) <= 1e-12:
            continue
        for sa, sb in itertools.product((0, 1), repeat=2):
            if so(p, sa) == so(r, sb) or so(q, sa) == so(s_, sb):
                continue
            terms.append(0.5 * v * _product(cr[so(p, sa)], cr[so(r, sb)], an[so(s_, sb)], an[so(q, sa)]))
    h = SparsePauliOp.sum(terms).simplify(atol=1e-10)
    return SparsePauliOp(h.paulis, np.real(h.coeffs))  # Hermitian: drop round-off imaginary parts


def spin_squared_operator(n_orbitals: int) -> SparsePauliOp:
    """Return a defensive copy; callers cannot change later spin checks."""
    return _cached_spin_squared_operator(n_orbitals).copy()


@lru_cache(maxsize=8)
def _cached_spin_squared_operator(n_orbitals: int) -> SparsePauliOp:
    """Total S squared in the alpha-block/beta-block occupation convention."""
    n = 2 * n_orbitals
    cr, an = _ladder(n)
    plus = SparsePauliOp.sum([_product(cr[i], an[i + n_orbitals]) for i in range(n_orbitals)])
    minus = plus.adjoint()
    sz = 0.5 * SparsePauliOp.sum(
        [_product(cr[i], an[i]) - _product(cr[i + n_orbitals], an[i + n_orbitals]) for i in range(n_orbitals)]
    )
    return (sz.dot(sz) + 0.5 * (plus.dot(minus) + minus.dot(plus))).simplify()


def number_operator(n_qubits: int) -> SparsePauliOp:
    cr, an = _ladder(n_qubits)
    return SparsePauliOp.sum([_product(cr[j], an[j]) for j in range(n_qubits)]).simplify()


@dataclass(frozen=True, eq=False)
class Excitation:
    label: str
    operator: SparsePauliOp  # T; the UCC generator is T - T^dagger


def uccsd_excitations(problem: ActiveSpaceProblem) -> tuple[Excitation, ...]:
    """Spin-conserving singles and doubles from the Hartree-Fock reference.

    Returns fresh operator copies: mutating them cannot affect the private cache or later callers.
    """
    return tuple(Excitation(e.label, e.operator.copy()) for e in _uccsd_excitations_cached(problem))


@lru_cache(maxsize=64)
def _uccsd_excitations_cached(problem: ActiveSpaceProblem) -> tuple[Excitation, ...]:
    n, nq = problem.n_orbitals, problem.n_qubits
    cr, an = _ladder(nq)
    occ = {0: range(problem.n_alpha), 1: range(problem.n_beta)}
    vir = {0: range(problem.n_alpha, n), 1: range(problem.n_beta, n)}
    spin_name = {0: "a", 1: "b"}

    def so(p: int, spin: int) -> int:
        return p + spin * n

    out: list[Excitation] = []
    for s in (0, 1):
        for i in occ[s]:
            for a in vir[s]:
                out.append(Excitation(f"{i}{spin_name[s]}->{a}{spin_name[s]}", _product(cr[so(a, s)], an[so(i, s)])))
    for s1, s2 in ((0, 0), (1, 1), (0, 1)):
        for i, j in itertools.product(occ[s1], occ[s2]):
            for a, b in itertools.product(vir[s1], vir[s2]):
                if s1 == s2 and not (i < j and a < b):
                    continue
                op = _product(cr[so(a, s1)], cr[so(b, s2)], an[so(j, s2)], an[so(i, s1)])
                label = f"{i}{spin_name[s1]}{j}{spin_name[s2]}->{a}{spin_name[s1]}{b}{spin_name[s2]}"
                out.append(Excitation(label, op))
    return tuple(out)


def sector_ground_energy(problem: ActiveSpaceProblem) -> float:
    """Exact diagonalisation of the qubit Hamiltonian in the (n_alpha, n_beta) sector."""
    n = problem.n_orbitals
    mask = (1 << n) - 1
    idx = [
        i
        for i in range(2**problem.n_qubits)
        if bin(i & mask).count("1") == problem.n_alpha and bin(i >> n).count("1") == problem.n_beta
    ]
    mat = qubit_hamiltonian(problem).to_matrix(sparse=True)[idx][:, idx].toarray()
    return float(np.linalg.eigvalsh(mat)[0])
