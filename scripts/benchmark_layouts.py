"""Reproduce the layout study cited in the README (no LLM involved; deterministic seeds).

Usage: python scripts/benchmark_layouts.py [snapshot.json]
Writes docs/benchmark.md, docs/benchmark.json and docs/figures/*.png.
"""

from __future__ import annotations

import itertools
import json
import sys
import time
from pathlib import Path

from quantivex import __version__, viz
from quantivex.data import load
from quantivex.experiment import compare_layouts, energy_curve
from quantivex.report import environment

ROOT = Path(__file__).resolve().parents[1]
DOCS = ROOT / "docs"
BONDS = (1.10, 1.50, 2.00)
SEED, SHOTS, N_RANDOM = 1234, 4000, 15
ROBUST_SEEDS = (11, 22, 33, 44, 55)


def robust_lines(snap) -> list[str]:  # type: ignore[no-untyped-def]
    import numpy as np

    from quantivex.chemistry import get_problem
    from quantivex.experiment import estimate_energy
    from quantivex.hardware import rank_chains
    from quantivex.vqe import run_vqe

    best = rank_chains(snap, 4, include_readout=False)[0].qubits
    out = []
    for r in BONDS:
        v = run_vqe(get_problem("N2", r))
        q, k, layouts = [], [], set()
        for seed in ROBUST_SEEDS:
            eq, ek = estimate_energy(v, snap, best, SHOTS, seed), estimate_energy(v, snap, None, SHOTS, seed)
            q.append(1000 * abs(eq.energy - v.problem.e_exact))
            k.append(1000 * abs(ek.energy - v.problem.e_exact))
            layouts.add(ek.layout)
        d = np.array(k) - np.array(q)
        n = len(ROBUST_SEEDS)

        def sem(x, n=n):  # type: ignore[no-untyped-def]
            return np.std(x, ddof=1) / np.sqrt(n)

        # Pre-specified paired test: exact two-sided sign-flip permutation of the per-seed differences.
        signs = np.array(list(itertools.product((1, -1), repeat=n)))
        p_value = float(np.mean(np.abs((signs * d).mean(axis=1)) >= abs(d.mean()) - 1e-12))
        out.append(
            f"| {r:.2f} | {np.mean(q):.1f} ± {sem(q):.1f} | {np.mean(k):.1f} ± {sem(k):.1f} | "
            f"{d.mean():+.1f} ± {sem(d):.1f} | {p_value:.3f} | {int((d > 0).sum())}/{n} | {len(layouts)} |"
        )
    return out


def main() -> None:
    snap = load(sys.argv[1] if len(sys.argv) > 1 else ROOT / "examples" / "ibm_torino_2025-02-26.json")
    (DOCS / "figures").mkdir(parents=True, exist_ok=True)
    results, lines = [], []
    start = time.perf_counter()
    for r in BONDS:
        comp = compare_layouts(snap, "N2", r, 2, 2, N_RANDOM, SHOTS, SEED)
        d = comp.describe()
        results.append(d)
        viz.plot_layout_comparison(comp, DOCS / "figures" / f"layouts_N2_{r:.2f}.png")
        if r == BONDS[-1]:
            best = comp.row("quantivex_best").estimate.layout
            viz.plot_chip_map(
                snap,
                DOCS / "figures" / "chip_map_torino.png",
                best,
                "Quantivex best chain",
                comp.row("qiskit_default").estimate.layout,
            )
        q = d["quantivex_vs_qiskit_error_mha"]
        worst = comp.row("worst_usable_chain").abs_error_ha * 1000
        lines.append(
            f"| {r:.2f} | {d['problem']['correlation_energy_mha']} | {q['quantivex_best']} | {q['qiskit_default']} "
            f"| ±{q['combined_two_sigma_mha']} | {worst:.1f} | {d['cost_vs_error_spearman_rho']} "
            f"({d['cost_vs_error_p_value']}, n={d['correlation_sample_size']}) | "
            f"{comp.row('quantivex_best').describe()['verdict']} |"
        )
    pts = energy_curve(
        "N2", [0.8, 1.0, 1.2, 1.4, 1.6, 1.8, 2.0, 2.2, 2.4], 2, 2, snap, results[-1]["rows"][0]["layout"], SHOTS, SEED
    )
    viz.plot_energy_curve(pts, DOCS / "figures" / "n2_curve_torino.png", "N2 CAS(2,2) on the best Torino chain")
    viz.plot_noise_blur(snap, DOCS / "figures" / "quantum_blur_torino.png")
    (DOCS / "benchmark.json").write_text(
        json.dumps({"environment": environment(), "dataset_sha256": snap.sha256, "results": results}, indent=2)
    )
    md = [
        "# Layout benchmark: N2 CAS(2,2) on ibm_torino calibration (2025-02-26)",
        "",
        f"Generated by `scripts/benchmark_layouts.py` with Quantivex {__version__}, seed {SEED}, {SHOTS} shots "
        "per measurement group, compact circuits, readout mitigation on (gate-only chain score), "
        f"{N_RANDOM} random chains per geometry; "
        "Spearman rho is computed over the random chains only. "
        f"Runtime {time.perf_counter() - start:.0f} s. Dataset SHA-256 `{snap.sha256}`.",
        "",
        "| R (Å) | correlation energy (mHa) | Quantivex best error (mHa) | Qiskit default error (mHa) "
        "| combined 2σ, descriptive (mHa) | worst chain error (mHa) | Spearman ρ(cost, error) (p) | verdict (best) |",
        "| --- | --- | --- | --- | --- | --- | --- | --- |",
        *lines,
        "",
        "Errors are |noisy - exact| after readout mitigation. The combined 2σ column is a descriptive shot-noise "
        "scale for a single seed, not a significance test; see the paired multi-seed analysis below. "
        "Verdicts use the 95% finite-sample radius (the tighter of Hoeffding and "
        "empirical Bernstein). The correlation uses random chains only; repeated geometries share chains.",
        "",
        "## Quantivex vs Qiskit across independent seeds",
        "",
        f"Seeds {', '.join(map(str, ROBUST_SEEDS))} (each changes shot noise and Qiskit's layout search). "
        "Mean |error| ± standard error of the mean; paired difference = Qiskit - Quantivex "
        "(positive = Quantivex better). The paired p-value is an exact two-sided sign-flip permutation test "
        f"over the {len(ROBUST_SEEDS)} seed pairs (chosen after these seeds had already been run once, "
        "in response to the v1.2.0 audit; no other test was tried). With "
        f"{len(ROBUST_SEEDS)} pairs the smallest attainable p is {2 / 2 ** len(ROBUST_SEEDS):.4f}, so this design "
        "cannot show significance at 0.05; more seeds, chips and dates would be needed. Seeds share one "
        "calibration snapshot, so this is not evidence about other devices.",
        "",
        "| R (Å) | Quantivex (mHa) | Qiskit default (mHa) | paired difference (mHa) | paired p | "
        "Quantivex better | distinct Qiskit layouts |",
        "| --- | --- | --- | --- | --- | --- | --- |",
        *robust_lines(snap),
        "",
    ]
    (DOCS / "benchmark.md").write_text("\n".join(md))
    print("\n".join(md))


if __name__ == "__main__":
    main()
